export interface BuiltInMuscle {
  id: string;
  name: string;
  group: string;
  subgroup: string | null;
  referenceUrl: string;
  groupOrder: number;
  muscleOrder: number;
}

function muscle(
  sequence: number,
  groupOrder: number,
  muscleOrder: number,
  group: string,
  name: string,
  referenceUrl: string,
  subgroup: string | null = null,
): BuiltInMuscle {
  return {
    id: `00000000-0000-4000-8000-${String(sequence).padStart(12, '0')}`,
    name,
    group,
    subgroup,
    referenceUrl,
    groupOrder,
    muscleOrder,
  };
}

